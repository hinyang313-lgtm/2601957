"""웹 버전 검증용 정답 자료(검증데이터.json)를 만든다.

웹 버전이 파이썬 버전과 같은 답을 내는지 확인하려면, 같은 그림에 대한 파이썬 쪽
중간 결과와 최종 확률이 있어야 한다. 이 스크립트가 그 정답 자료를 만든다.

표본은 두 무리로 나뉜다.

  확대 무리 (200장)
      MNIST 시험 그림을 최근접 이웃으로 10배 확대해 280x280으로 만든 것.
      기준 정확도(97% 이상)를 재는 무리이다.

  획 무리 (25장)
      app.py의 그리기 함수(획그리기)로 PIL에 직접 획을 그린 것.
      확대 무리는 크기가 언제나 10의 배수여서, 사람이 마우스로 그렸을 때만 생기는
      상황(어중간한 크기, 부드러운 획 가장자리)을 한 번도 시험하지 못한다.
      그 빈틈을 메우는 무리이다. 통과 기준에는 넣지 않고 따로 보고한다.

만들어지는 파일은 약 30MB이므로 깃에 넣지 않는다(.gitignore 참고).

실행:
    cd desktop_version
    python3 검증데이터만들기.py
"""

import base64
import json
import math
import os
import random

import numpy as np
import torch
from PIL import Image, ImageDraw
from torchvision import datasets

from app import 획그리기, 모델불러오기, 캔버스크기, 펜굵기
from preprocess import 전처리, 정규화, 정규화_평균, 정규화_표준편차

이폴더 = os.path.dirname(os.path.abspath(__file__))
자료폴더 = os.path.join(이폴더, "data")
웹폴더 = os.path.join(os.path.dirname(이폴더), "web_version")
결과경로 = os.path.join(웹폴더, "검증데이터.json")

확대표본수 = 200
획표본수 = 25
확대배수 = 10  # 28 x 10 = 280


def 원호(중심가로, 중심세로, 반지름가로, 반지름세로, 시작각, 끝각, 개수=16):
    """각도(도)를 받아 타원 위의 점들을 낸다. 세로는 아래로 증가한다."""
    점들 = []
    for 번호 in range(개수 + 1):
        각 = math.radians(시작각 + (끝각 - 시작각) * 번호 / 개수)
        점들.append(
            (중심가로 + 반지름가로 * math.cos(각), 중심세로 + 반지름세로 * math.sin(각))
        )
    return 점들


def 숫자획(숫자):
    """0~1 좌표계(가로, 세로)에서 숫자 하나를 그리는 획 목록.

    각도는 도(degree)이고, 0도가 오른쪽, 90도가 아래쪽이다(세로축이 아래로 증가).
    """
    if 숫자 == 0:
        return [원호(0.5, 0.5, 0.4, 0.47, -90, 270, 28)]
    if 숫자 == 1:
        return [[(0.28, 0.2), (0.5, 0.05), (0.5, 0.96)]]
    if 숫자 == 2:
        return [
            원호(0.5, 0.24, 0.33, 0.2, 200, 390, 16)
            + [(0.12, 0.94), (0.92, 0.94)]
        ]
    if 숫자 == 3:
        return [
            원호(0.5, 0.27, 0.31, 0.25, 200, 450, 18)
            + 원호(0.5, 0.72, 0.35, 0.26, 270, 470, 20)
        ]
    if 숫자 == 4:
        return [[(0.66, 0.04), (0.08, 0.68), (0.94, 0.68)], [(0.66, 0.04), (0.66, 0.96)]]
    if 숫자 == 5:
        return [
            [(0.85, 0.06), (0.28, 0.06), (0.24, 0.44)]
            + 원호(0.44, 0.7, 0.34, 0.26, 250, 470, 18)
        ]
    if 숫자 == 6:
        return [
            원호(0.5, 0.5, 0.33, 0.46, 315, 90, 20)
            + 원호(0.5, 0.72, 0.3, 0.25, 90, 450, 18)
        ]
    if 숫자 == 7:
        return [[(0.1, 0.08), (0.9, 0.08), (0.36, 0.96)]]
    if 숫자 == 8:
        return [
            원호(0.5, 0.28, 0.28, 0.26, 90, 450, 20)
            + 원호(0.5, 0.74, 0.34, 0.24, 270, 630, 22)
        ]
    if 숫자 == 9:
        return [원호(0.52, 0.27, 0.28, 0.25, 0, 360, 22) + [(0.72, 0.96)]]
    raise ValueError(숫자)


def 획으로그리기(숫자, 왼쪽, 위, 폭, 높이):
    """획 목록을 280x280 그림에 그린다. app.py와 같은 굵기, 같은 캔버스 크기."""
    그림 = Image.new("L", (캔버스크기, 캔버스크기), 0)
    그리기 = ImageDraw.Draw(그림)
    for 획 in 숫자획(숫자):
        점들 = [(왼쪽 + 가로 * 폭, 위 + 세로 * 높이) for 가로, 세로 in 획]
        획그리기(그리기, 점들, 펜굵기)
    return 그림


def 표본모으기():
    """(이름, 종류, 정답, 280x280 흑백 그림) 목록을 만든다."""
    표본들 = []

    시험자료 = datasets.MNIST(자료폴더, train=False, download=True)
    for 번호 in range(확대표본수):
        작은그림, 정답 = 시험자료[번호]
        큰그림 = 작은그림.resize(
            (28 * 확대배수, 28 * 확대배수), Image.NEAREST
        ).convert("L")
        표본들.append((f"확대-{번호:03d}", "확대", int(정답), 큰그림))

    뽑기 = random.Random(2026)
    for 번호 in range(획표본수):
        숫자 = 번호 % 10
        크기 = 뽑기.randint(150, 250)
        폭 = int(크기 * 뽑기.uniform(0.55, 0.85))
        여유가로 = 캔버스크기 - 폭 - 펜굵기
        여유세로 = 캔버스크기 - 크기 - 펜굵기
        왼쪽 = 펜굵기 / 2 + 뽑기.randint(0, max(0, 여유가로))
        위 = 펜굵기 / 2 + 뽑기.randint(0, max(0, 여유세로))
        표본들.append(
            (f"획-{번호:03d}", "획", 숫자, 획으로그리기(숫자, 왼쪽, 위, 폭, 크기))
        )
    return 표본들


def main():
    os.makedirs(웹폴더, exist_ok=True)
    모델 = 모델불러오기()
    표본들 = 표본모으기()

    담을것 = []
    맞은수 = {"확대": 0, "획": 0}
    전체수 = {"확대": 0, "획": 0}

    for 이름, 종류, 정답, 그림 in 표본들:
        배열 = np.array(그림, dtype=np.uint8)
        스물여덟 = 전처리(배열)
        if 스물여덟 is None:
            raise ValueError(f"{이름}: 빈 그림이 만들어졌습니다")
        입력 = 정규화(스물여덟).reshape(1, 1, 28, 28)
        with torch.no_grad():
            확률 = torch.softmax(모델(torch.from_numpy(입력)), dim=1)[0].numpy()
        예측 = int(np.argmax(확률))
        전체수[종류] += 1
        if 예측 == 정답:
            맞은수[종류] += 1

        담을것.append(
            {
                "이름": 이름,
                "종류": 종류,
                "정답": 정답,
                "그림가로": 캔버스크기,
                "그림세로": 캔버스크기,
                "그림base64": base64.b64encode(배열.tobytes()).decode("ascii"),
                "파이썬전처리": [round(float(값), 7) for 값 in 스물여덟.reshape(-1)],
                "파이썬확률": [float(값) for 값 in 확률],
                "파이썬예측": 예측,
            }
        )

    결과 = {
        "설명": "web_version/검증.html이 쓰는 정답 자료",
        "만든이": "desktop_version/검증데이터만들기.py",
        "캔버스크기": 캔버스크기,
        "펜굵기": 펜굵기,
        "정규화": {"평균": 정규화_평균, "표준편차": 정규화_표준편차},
        "표본": 담을것,
    }
    with open(결과경로, "w", encoding="utf-8") as 파일:
        json.dump(결과, 파일, ensure_ascii=False)
        파일.write("\n")

    print(f"{결과경로}  {os.path.getsize(결과경로) / 1e6:.1f} MB, 표본 {len(담을것)}개")
    for 종류 in ("확대", "획"):
        if 전체수[종류]:
            비율 = 맞은수[종류] / 전체수[종류] * 100
            print(f"파이썬 정확도({종류}): {비율:.1f}%  ({맞은수[종류]}/{전체수[종류]})")


if __name__ == "__main__":
    main()
