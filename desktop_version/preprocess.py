"""그린 그림을 모델 입력 형식(28x28)으로 바꾸는 전처리.

전처리는 3단계이다.

1) 여백 자르기    : 숫자가 실제로 있는 사각형만 남긴다.
2) 비율 유지 축소 : 긴 변을 20픽셀에 맞추고 가로세로 비율은 유지한다.
3) 무게중심 이동  : 밝기 무게중심을 28x28 그림의 중앙(13.5, 13.5)으로 옮긴다.

MNIST 자체가 이 3단계로 만들어진 자료이므로, 사람이 그린 그림도 같은 방법으로
다듬어야 학습한 모델이 제대로 맞힌다.

web_version/전처리.js가 이 파일을 그대로 옮긴 것이다. 다만 2단계의 축소만
다르다. PIL의 LANCZOS를 브라우저에서 똑같이 재현할 수 없어 자바스크립트에서는
면적 평균 축소를 쓴다(자세한 내용은 web_version/CLAUDE.md 참고).

그림은 언제나 "검은 바탕에 흰 숫자"인 흑백(L) 그림으로 다룬다. app.py의 그림판과
MNIST 원본이 모두 이 형식이다.
"""

import math

import numpy as np
from PIL import Image

# MNIST 학습 자료의 밝기 평균과 표준편차. 웹 버전은 이 값을 코드에 적는 대신
# 가중치정보.json에서 읽어 쓴다(값의 출처를 파이썬 하나로 유지하기 위함).
정규화_평균 = 0.1307
정규화_표준편차 = 0.3081

# 축소 목표 크기와 최종 그림 크기.
축소_목표 = 20
최종_크기 = 28


def 반올림(값):
    """0.5를 언제나 위로 올리는 반올림.

    파이썬 내장 round()는 0.5를 짝수로 보내고(round-half-to-even),
    자바스크립트 Math.round()는 위로 올린다. 두 버전의 결과를 같게 하려고
    양쪽 모두 floor(값 + 0.5)로 맞춘다.
    """
    return math.floor(값 + 0.5)


def 그림을배열로(그림):
    """PIL 그림이나 배열을 2차원 uint8 배열로 만든다."""
    if isinstance(그림, np.ndarray):
        배열 = 그림
    else:
        배열 = np.array(그림.convert("L"))
    if 배열.ndim != 2:
        raise ValueError("2차원 흑백 그림이어야 합니다.")
    return 배열.astype(np.uint8)


def 여백자르기(배열):
    """밝은 점이 있는 가장 작은 사각형만 남긴다. 아무것도 없으면 None."""
    있는곳 = 배열 > 0
    if not 있는곳.any():
        return None
    행있음 = np.where(있는곳.any(axis=1))[0]
    열있음 = np.where(있는곳.any(axis=0))[0]
    위, 아래 = int(행있음[0]), int(행있음[-1])
    왼쪽, 오른쪽 = int(열있음[0]), int(열있음[-1])
    return 배열[위 : 아래 + 1, 왼쪽 : 오른쪽 + 1]


def 비율유지축소(배열):
    """긴 변이 20픽셀이 되도록 비율을 유지하며 줄인다."""
    높이, 너비 = 배열.shape
    비율 = 축소_목표 / max(높이, 너비)
    새높이 = max(1, 반올림(높이 * 비율))
    새너비 = max(1, 반올림(너비 * 비율))
    줄인그림 = Image.fromarray(배열).resize((새너비, 새높이), Image.LANCZOS)
    return np.array(줄인그림, dtype=np.uint8)


def 무게중심이동(배열):
    """28x28 바탕에 올리고, 밝기 무게중심을 중앙으로 옮긴다."""
    높이, 너비 = 배열.shape
    바탕 = np.zeros((최종_크기, 최종_크기), dtype=np.uint8)
    상 = (최종_크기 - 높이) // 2
    좌 = (최종_크기 - 너비) // 2
    바탕[상 : 상 + 높이, 좌 : 좌 + 너비] = 배열

    무게 = float(바탕.sum())
    if 무게 == 0:
        return 바탕

    좌표 = np.arange(최종_크기, dtype=np.float64)
    무게중심행 = float((바탕.sum(axis=1) * 좌표).sum()) / 무게
    무게중심열 = float((바탕.sum(axis=0) * 좌표).sum()) / 무게
    중앙 = (최종_크기 - 1) / 2.0  # 13.5
    이동행 = 반올림(중앙 - 무게중심행)
    이동열 = 반올림(중앙 - 무게중심열)

    결과 = np.zeros((최종_크기, 최종_크기), dtype=np.uint8)
    받는행시작 = max(0, 이동행)
    받는열시작 = max(0, 이동열)
    주는행시작 = max(0, -이동행)
    주는열시작 = max(0, -이동열)
    옮길높이 = 최종_크기 - max(이동행, -이동행)
    옮길너비 = 최종_크기 - max(이동열, -이동열)
    if 옮길높이 > 0 and 옮길너비 > 0:
        결과[받는행시작 : 받는행시작 + 옮길높이, 받는열시작 : 받는열시작 + 옮길너비] = 바탕[
            주는행시작 : 주는행시작 + 옮길높이, 주는열시작 : 주는열시작 + 옮길너비
        ]
    return 결과


def 전처리(그림):
    """그린 그림을 0~1 범위의 28x28 float32 배열로 바꾼다.

    아무것도 그리지 않았으면 None을 낸다.
    """
    배열 = 그림을배열로(그림)
    잘린것 = 여백자르기(배열)
    if 잘린것 is None:
        return None
    줄인것 = 비율유지축소(잘린것)
    옮긴것 = 무게중심이동(줄인것)
    return (옮긴것.astype(np.float32) / 255.0).astype(np.float32)


def 정규화(배열):
    """0~1 밝기를 MNIST 평균과 표준편차로 정규화한다."""
    return ((np.asarray(배열, dtype=np.float32) - 정규화_평균) / 정규화_표준편차).astype(
        np.float32
    )


def 모델입력만들기(그림):
    """전처리와 정규화를 거쳐 (1, 1, 28, 28) 모양 텐서용 배열을 만든다."""
    스물여덟 = 전처리(그림)
    if 스물여덟 is None:
        return None
    return 정규화(스물여덟).reshape(1, 1, 최종_크기, 최종_크기)
