// 그린 그림을 모델 입력 형식(28x28)으로 바꾸는 전처리.
//
// desktop_version/preprocess.py를 자바스크립트로 옮긴 것이다. 3단계 모두 파이썬과
// 같은 순서, 같은 계산이다.
//
//   1) 여백 자르기    : 숫자가 있는 사각형만 남긴다.
//   2) 비율 유지 축소 : 긴 변을 20픽셀에 맞추고 비율은 유지한다.
//   3) 무게중심 이동  : 밝기 무게중심을 28x28의 중앙(13.5, 13.5)으로 옮긴다.
//
// 딱 한 곳만 다르다. 파이썬은 PIL의 LANCZOS로 줄이는데, 브라우저에서 LANCZOS를
// 그대로 재현할 수 없어 여기서는 면적 평균 축소를 직접 구현했다. 그래서 28x28
// 중간 결과는 파이썬과 조금 다르고, 최종 정답률은 같은 수준이 나온다
// (검증.html이 이것을 확인한다).
//
// 그림은 {폭, 높이, 값} 꼴의 객체로 다룬다. 값은 0~255 밝기가 한 줄씩 이어진
// 1차원 배열이고, "검은 바탕에 흰 숫자"이다.

export const 축소_목표 = 20;
export const 최종_크기 = 28;

// 파이썬 내장 round()는 0.5를 짝수로 보내지만 자바스크립트 Math.round()는 위로
// 올린다. 두 버전의 결과를 같게 하려고 양쪽 모두 floor(값 + 0.5)를 쓴다.
export function 반올림(값) {
  return Math.floor(값 + 0.5);
}

export function 그림만들기(폭, 높이, 값) {
  return { 폭, 높이, 값: 값 ?? new Float32Array(폭 * 높이) };
}

// 1단계. 밝은 점이 있는 가장 작은 사각형만 남긴다. 아무것도 없으면 null.
export function 여백자르기(그림) {
  const { 폭, 높이, 값 } = 그림;
  let 위 = Infinity;
  let 아래 = -Infinity;
  let 왼쪽 = Infinity;
  let 오른쪽 = -Infinity;
  for (let 세로 = 0; 세로 < 높이; 세로 += 1) {
    for (let 가로 = 0; 가로 < 폭; 가로 += 1) {
      if (값[세로 * 폭 + 가로] > 0) {
        if (세로 < 위) 위 = 세로;
        if (세로 > 아래) 아래 = 세로;
        if (가로 < 왼쪽) 왼쪽 = 가로;
        if (가로 > 오른쪽) 오른쪽 = 가로;
      }
    }
  }
  if (아래 < 위 || 오른쪽 < 왼쪽) return null;

  const 새폭 = 오른쪽 - 왼쪽 + 1;
  const 새높이 = 아래 - 위 + 1;
  const 새값 = new Float32Array(새폭 * 새높이);
  for (let 세로 = 0; 세로 < 새높이; 세로 += 1) {
    for (let 가로 = 0; 가로 < 새폭; 가로 += 1) {
      새값[세로 * 새폭 + 가로] = 값[(위 + 세로) * 폭 + (왼쪽 + 가로)];
    }
  }
  return 그림만들기(새폭, 새높이, 새값);
}

// 면적 평균 축소. 목표 픽셀 하나가 덮는 원본 영역의 밝기를 면적으로 가중 평균한다.
//
// 원본 경계를 넘지 않도록 끝 좌표를 Math.min으로 자른다. 부동소수점 때문에
// (번호 + 1) * 비율이 원본 크기를 아주 조금 넘는 경우가 실제로 있다.
// 예: 19 * (21 / 19) === 21.000000000000004. 자르지 않으면 배열 밖을 읽어
// 결과가 조용히 망가진다.
export function 면적평균축소(그림, 새폭, 새높이) {
  const { 폭, 높이, 값 } = 그림;
  const 가로비 = 폭 / 새폭;
  const 세로비 = 높이 / 새높이;
  const 새값 = new Float32Array(새폭 * 새높이);

  for (let 세로 = 0; 세로 < 새높이; 세로 += 1) {
    const 세로시작 = 세로 * 세로비;
    const 세로끝 = Math.min(높이, (세로 + 1) * 세로비);
    const 첫행 = Math.floor(세로시작);
    const 끝행 = Math.max(첫행 + 1, Math.ceil(세로끝));

    for (let 가로 = 0; 가로 < 새폭; 가로 += 1) {
      const 가로시작 = 가로 * 가로비;
      const 가로끝 = Math.min(폭, (가로 + 1) * 가로비);
      const 첫열 = Math.floor(가로시작);
      const 끝열 = Math.max(첫열 + 1, Math.ceil(가로끝));

      let 밝기합 = 0;
      let 넓이합 = 0;
      for (let 원본행 = 첫행; 원본행 < 끝행 && 원본행 < 높이; 원본행 += 1) {
        const 세로겹침 =
          Math.min(원본행 + 1, 세로끝) - Math.max(원본행, 세로시작);
        if (세로겹침 <= 0) continue;
        for (let 원본열 = 첫열; 원본열 < 끝열 && 원본열 < 폭; 원본열 += 1) {
          const 가로겹침 =
            Math.min(원본열 + 1, 가로끝) - Math.max(원본열, 가로시작);
          if (가로겹침 <= 0) continue;
          const 넓이 = 세로겹침 * 가로겹침;
          밝기합 += 값[원본행 * 폭 + 원본열] * 넓이;
          넓이합 += 넓이;
        }
      }
      새값[세로 * 새폭 + 가로] = 밝기합 / 넓이합;
    }
  }
  return 그림만들기(새폭, 새높이, 새값);
}

// 2단계. 긴 변이 20픽셀이 되도록 비율을 유지하며 줄인다.
// 파이썬이 uint8로 저장하므로 여기서도 0~255 정수로 맞춰 둔다.
export function 비율유지축소(그림) {
  const 비율 = 축소_목표 / Math.max(그림.높이, 그림.폭);
  const 새높이 = Math.max(1, 반올림(그림.높이 * 비율));
  const 새폭 = Math.max(1, 반올림(그림.폭 * 비율));
  const 줄인것 = 면적평균축소(그림, 새폭, 새높이);
  for (let 자리 = 0; 자리 < 줄인것.값.length; 자리 += 1) {
    줄인것.값[자리] = Math.min(255, Math.max(0, 반올림(줄인것.값[자리])));
  }
  return 줄인것;
}

// 3단계. 28x28 바탕에 올리고 밝기 무게중심을 중앙으로 옮긴다.
export function 무게중심이동(그림) {
  const 바탕 = new Float32Array(최종_크기 * 최종_크기);
  const 상 = Math.floor((최종_크기 - 그림.높이) / 2);
  const 좌 = Math.floor((최종_크기 - 그림.폭) / 2);
  for (let 세로 = 0; 세로 < 그림.높이; 세로 += 1) {
    for (let 가로 = 0; 가로 < 그림.폭; 가로 += 1) {
      바탕[(상 + 세로) * 최종_크기 + (좌 + 가로)] = 그림.값[세로 * 그림.폭 + 가로];
    }
  }

  let 무게 = 0;
  let 세로합 = 0;
  let 가로합 = 0;
  for (let 세로 = 0; 세로 < 최종_크기; 세로 += 1) {
    for (let 가로 = 0; 가로 < 최종_크기; 가로 += 1) {
      const 밝기 = 바탕[세로 * 최종_크기 + 가로];
      무게 += 밝기;
      세로합 += 밝기 * 세로;
      가로합 += 밝기 * 가로;
    }
  }
  if (무게 === 0) return 그림만들기(최종_크기, 최종_크기, 바탕);

  const 중앙 = (최종_크기 - 1) / 2; // 13.5
  const 이동행 = 반올림(중앙 - 세로합 / 무게);
  const 이동열 = 반올림(중앙 - 가로합 / 무게);

  const 결과 = new Float32Array(최종_크기 * 최종_크기);
  for (let 세로 = 0; 세로 < 최종_크기; 세로 += 1) {
    const 받는행 = 세로 + 이동행;
    if (받는행 < 0 || 받는행 >= 최종_크기) continue;
    for (let 가로 = 0; 가로 < 최종_크기; 가로 += 1) {
      const 받는열 = 가로 + 이동열;
      if (받는열 < 0 || 받는열 >= 최종_크기) continue;
      결과[받는행 * 최종_크기 + 받는열] = 바탕[세로 * 최종_크기 + 가로];
    }
  }
  return 그림만들기(최종_크기, 최종_크기, 결과);
}

// 전처리 3단계를 모두 거쳐 0~1 범위의 28x28 값 784개를 낸다.
// 아무것도 그리지 않았으면 null.
export function 전처리(그림) {
  const 잘린것 = 여백자르기(그림);
  if (잘린것 === null) return null;
  const 줄인것 = 비율유지축소(잘린것);
  const 옮긴것 = 무게중심이동(줄인것);
  const 결과 = new Float32Array(최종_크기 * 최종_크기);
  for (let 자리 = 0; 자리 < 결과.length; 자리 += 1) {
    결과[자리] = 옮긴것.값[자리] / 255;
  }
  return 결과;
}

// 0~1 밝기를 MNIST 평균과 표준편차로 정규화한다.
// 상수는 코드에 적지 않고 가중치정보.json에서 읽어 넘긴다.
export function 정규화(값들, 평균, 표준편차) {
  const 결과 = new Float32Array(값들.length);
  for (let 자리 = 0; 자리 < 값들.length; 자리 += 1) {
    결과[자리] = (값들[자리] - 평균) / 표준편차;
  }
  return 결과;
}
